    public void save(String dbName) throws TorqueException
    {
        Connection con = null;
        try
        {
            con = Transaction.begin(dbName);
            save(con);
            Transaction.commit(con);
        }
        catch(TorqueException e)
        {
            Transaction.safeRollback(con);
            throw e;
        }
    }

    /** flag to prevent endless save loop, if this object is referenced
        by another object which falls in this transaction. */
    private boolean alreadyInSave = false;
    /**
     * Stores the object in the database.  If the object is new,
     * it inserts it; otherwise an update is performed.  This method
     * is meant to be used as part of a transaction, otherwise use
     * the save() method and the connection details will be handled
     * internally
     *
     * @param con
     * @throws TorqueException
     */
    public void save(Connection con) throws TorqueException
    {
        if (!alreadyInSave)
        {
            alreadyInSave = true;



            // If this object has been modified, then save it to the database.
            if (isModified())
            {
                if (isNew())
                {
                    DBMachinePeer.doInsert((DBMachine) this, con);
                    setNew(false);
                }
                else
                {
                    DBMachinePeer.doUpdate((DBMachine) this, con);
                }
            }


            if (collDBMachineDBUserExcludeds != null)
            {
                for (int i = 0; i < collDBMachineDBUserExcludeds.size(); i++)
                {
                    ((DBMachineDBUserExcluded) collDBMachineDBUserExcludeds.get(i)).save(con);
                }
            }

            if (collDBMachineConditions != null)
            {
                for (int i = 0; i < collDBMachineConditions.size(); i++)
                {
                    ((DBMachineCondition) collDBMachineConditions.get(i)).save(con);
                }
            }

            if (collDBExperimentDBMachines != null)
            {
                for (int i = 0; i < collDBExperimentDBMachines.size(); i++)
                {
                    ((DBExperimentDBMachine) collDBExperimentDBMachines.get(i)).save(con);
                }
            }

            if (collDBExcludingExperimentss != null)
            {
                for (int i = 0; i < collDBExcludingExperimentss.size(); i++)
                {
                    ((DBExcludingExperiments) collDBExcludingExperimentss.get(i)).save(con);
                }
            }

            if (collDBSamples != null)
            {
                for (int i = 0; i < collDBSamples.size(); i++)
                {
                    ((DBSample) collDBSamples.get(i)).save(con);
                }
            }
            alreadyInSave = false;
        }
    }


