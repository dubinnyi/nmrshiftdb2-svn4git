    /**
     * selects a collection of DBMachine objects pre-filled with their
     * DBLabGroup objects.
     *
     * This method is protected by default in order to keep the public
     * api reasonable.  You can provide public methods for those you
     * actually need in DBMachinePeer.
     *
     * @throws TorqueException Any exceptions caught during processing will be
     *         rethrown wrapped into a TorqueException.
     */
    protected static List<DBMachine> doSelectJoinDBLabGroup(Criteria criteria, Connection conn)
        throws TorqueException
    {
        setDbName(criteria);

        DBMachinePeer.addSelectColumns(criteria);
        int offset = numColumns + 1;
        DBLabGroupPeer.addSelectColumns(criteria);

        criteria.addJoin(DBMachinePeer.LABGROUP_ID,
            DBLabGroupPeer.LABGROUP_ID);

        correctBooleans(criteria);

        List<Record> rows;
        if (conn == null)
        {
            rows = BasePeer.doSelect(criteria);
        }
        else
        {
            rows = BasePeer.doSelect(criteria,conn);
        }

        List<DBMachine> results = new ArrayList<DBMachine>();

        for (int i = 0; i < rows.size(); i++)
        {
            Record row =  rows.get(i);

            Class omClass = DBMachinePeer.getOMClass();
            DBMachine obj1 = (DBMachine) DBMachinePeer
                .row2Object(row, 1, omClass);
             omClass = DBLabGroupPeer.getOMClass();
            DBLabGroup obj2 = (DBLabGroup) DBLabGroupPeer
                .row2Object(row, offset, omClass);

            boolean newObject = true;
            for (int j = 0; j < results.size(); j++)
            {
                DBMachine temp_obj1 =  results.get(j);
                DBLabGroup temp_obj2 = (DBLabGroup) temp_obj1.getDBLabGroup();
                if (temp_obj2.getPrimaryKey().equals(obj2.getPrimaryKey()))
                {
                    newObject = false;
                    temp_obj2.addDBMachine(obj1);
                    break;
                }
            }
            if (newObject)
            {
                obj2.initDBMachines();
                obj2.addDBMachine(obj1);
            }
            results.add(obj1);
        }
        return results;
    }




