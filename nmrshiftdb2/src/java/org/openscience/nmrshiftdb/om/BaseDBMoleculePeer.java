    /**
     * selects a collection of DBMolecule objects pre-filled with their
     * NmrshiftdbUser objects.
     *
     * This method is protected by default in order to keep the public
     * api reasonable.  You can provide public methods for those you
     * actually need in DBMoleculePeer.
     *
     * @throws TorqueException Any exceptions caught during processing will be
     *         rethrown wrapped into a TorqueException.
     */
    protected static List<DBMolecule> doSelectJoinNmrshiftdbUser(Criteria criteria, Connection conn)
        throws TorqueException
    {
        setDbName(criteria);

        DBMoleculePeer.addSelectColumns(criteria);
        int offset = numColumns + 1;
        NmrshiftdbUserPeer.addSelectColumns(criteria);

        criteria.addJoin(DBMoleculePeer.USER_ID,
            NmrshiftdbUserPeer.USER_ID);

        correctBooleans(criteria);

        List<Record> rows;
        if (conn == null)
        {
            rows = BasePeer.doSelect(criteria);
        }
        else
        {
            rows = BasePeer.doSelect(criteria,conn);
        }

        List<DBMolecule> results = new ArrayList<DBMolecule>();

        for (int i = 0; i < rows.size(); i++)
        {
            Record row =  rows.get(i);

            Class omClass = DBMoleculePeer.getOMClass();
            DBMolecule obj1 = (DBMolecule) DBMoleculePeer
                .row2Object(row, 1, omClass);
             omClass = NmrshiftdbUserPeer.getOMClass();
            NmrshiftdbUser obj2 = (NmrshiftdbUser) NmrshiftdbUserPeer
                .row2Object(row, offset, omClass);

            boolean newObject = true;
            for (int j = 0; j < results.size(); j++)
            {
                DBMolecule temp_obj1 =  results.get(j);
                NmrshiftdbUser temp_obj2 = (NmrshiftdbUser) temp_obj1.getNmrshiftdbUser();
                if (temp_obj2.getPrimaryKey().equals(obj2.getPrimaryKey()))
                {
                    newObject = false;
                    temp_obj2.addDBMolecule(obj1);
                    break;
                }
            }
            if (newObject)
            {
                obj2.initDBMolecules();
                obj2.addDBMolecule(obj1);
            }
            results.add(obj1);
        }
        return results;
    }




