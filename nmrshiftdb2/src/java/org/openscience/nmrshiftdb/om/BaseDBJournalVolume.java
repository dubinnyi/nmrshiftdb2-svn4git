    protected DBJournalVolume copyInto(DBJournalVolume copyObj, boolean deepcopy) throws TorqueException
    {
        copyObj.setJournalVolumeId(journalVolumeId);
        copyObj.setVolume(volume);
        copyObj.setYear(year);
        copyObj.setJournalId(journalId);

        copyObj.setJournalVolumeId( 0);

        if (deepcopy)
        {


        List<DBArticle> vDBArticles = getDBArticles();
        if (vDBArticles != null)
        {
            for (int i = 0; i < vDBArticles.size(); i++)
            {
                DBArticle obj =  vDBArticles.get(i);
                copyObj.addDBArticle(obj.copy());
            }
        }
        else
        {
            copyObj.collDBArticles = null;
        }
        }
        return copyObj;
    }
        
    
