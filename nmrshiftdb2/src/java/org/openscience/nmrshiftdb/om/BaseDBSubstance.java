    /**
     * Fills the copyObj with the contents of this object.
     * If deepcopy is true, The associated objects are also copied
     * and treated as new objects.
     *
     * @param copyObj the object to fill.
     * @param deepcopy whether the associated objects should be copied.
     */
    protected DBSubstance copyInto(DBSubstance copyObj, boolean deepcopy) throws TorqueException
    {
        copyObj.setSubstanceId(substanceId);
        copyObj.setUserId(userId);
        copyObj.setSubstanceComment(substanceComment);

        copyObj.setSubstanceId( 0);

        if (deepcopy)
        {


        List<DBSpectrum> vDBSpectrums = getDBSpectrums();
        if (vDBSpectrums != null)
        {
            for (int i = 0; i < vDBSpectrums.size(); i++)
            {
                DBSpectrum obj =  vDBSpectrums.get(i);
                copyObj.addDBSpectrum(obj.copy());
            }
        }
        else
        {
            copyObj.collDBSpectrums = null;
        }
        }
        return copyObj;
    }
        
    
